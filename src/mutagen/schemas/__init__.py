# ── Experiment Schemas ───────────────────────────────────────

class ExperimentConfig(BaseModel):
    """Configuration for an evolution experiment."""
    source_file: str
    user_id: Optional[str] = None
    project_id: Optional[str] = None
    language: ProgrammingLanguage = ProgrammingLanguage.PYTHON
    objective: OptimizationObjective = OptimizationObjective.BALANCED
    generations: int = Field(default=5, ge=1, le=100)
    population_size: int = Field(default=4, ge=1, le=20)
    benchmark_repetitions: int = Field(default=5, ge=1, le=100)
    execution_timeout: int = Field(default=30, ge=1, le=600)
    memory_limit_mb: int = Field(default=256, ge=32, le=4096)
    test_command: Optional[str] = None
    fitness_weights: dict[str, float] = Field(default_factory=lambda: {
        "speed": 0.50, "memory": 0.25, "complexity": 0.15, "maintainability": 0.10
    })
    dry_run: bool = False
    stop_on_stagnation: bool = False


class ExperimentSummary(BaseModel):
    """Summary of an experiment for display."""
    experiment_id: str
    project_id: Optional[str] = None
    status: ExperimentStatus
    source_file: str
    language: ProgrammingLanguage
    objective: OptimizationObjective
    generations_completed: int = 0
    generations_total: int = 0
    total_candidates: int = 0
    valid_candidates: int = 0
    best_candidate_id: Optional[str] = None
    best_improvement_percent: Optional[float] = None
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None
    duration_seconds: Optional[float] = None


