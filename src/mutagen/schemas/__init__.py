"""
Pydantic schemas for MUTAGEN data transfer.

These schemas are used for validation, serialization, and CLI output.
They are independent of the database models.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field, field_validator


# ── Enums ────────────────────────────────────────────────────

class ProgrammingLanguage(str, Enum):
    PYTHON = "python"
    JAVASCRIPT = "javascript"
    TYPESCRIPT = "typescript"
    JAVA = "java"
    C = "c"
    CPP = "cpp"
    GO = "go"
    RUST = "rust"
    UNKNOWN = "unknown"


class ExperimentStatus(str, Enum):
    QUEUED = "queued"
    RUNNING = "running"
    SUCCEEDED = "succeeded"
    FAILED = "failed"
    CANCELLED = "cancelled"
    TIMED_OUT = "timed_out"


class CandidateStatus(str, Enum):
    PENDING = "pending"
    VALIDATING = "validating"
    VALID = "valid"
    REJECTED = "rejected"
    TESTING = "testing"
    TESTED = "tested"
    BENCHMARKING = "benchmarking"
    BENCHMARKED = "benchmarked"
    FAILED = "failed"
    BEST_ELIGIBLE = "best_eligible"


class MutationStrategy(str, Enum):
    ALGORITHMIC = "algorithmic"
    DATA_STRUCTURE = "data_structure"
    CACHING = "caching"
    LOOP_OPTIMIZATION = "loop_optimization"
    MEMORY_REDUCTION = "memory_reduction"
    CONTROL_FLOW = "control_flow"
    REDUNDANCY_ELIMINATION = "redundancy_elimination"
    LANGUAGE_SPECIFIC = "language_specific"
    GENERAL = "general"


class OptimizationObjective(str, Enum):
    SPEED = "speed"
    MEMORY = "memory"
    BALANCED = "balanced"


class MemoryType(str, Enum):
    PROJECT = "project"
    EVOLUTION = "evolution"
    SEMANTIC = "semantic"


# ── Code Analysis Schemas ────────────────────────────────────

class FunctionInfo(BaseModel):
    """Information about a detected function."""
    name: str
    lineno: int
    end_lineno: Optional[int] = None
    args: list[str] = Field(default_factory=list)
    decorators: list[str] = Field(default_factory=list)
    docstring: Optional[str] = None
    is_async: bool = False
    complexity: int = 1


class ClassInfo(BaseModel):
    """Information about a detected class."""
    name: str
    lineno: int
    end_lineno: Optional[int] = None
    bases: list[str] = Field(default_factory=list)
    methods: list[FunctionInfo] = Field(default_factory=list)
    decorators: list[str] = Field(default_factory=list)
    docstring: Optional[str] = None


class ImportInfo(BaseModel):
    """Information about an import statement."""
    module: str
    names: list[str] = Field(default_factory=list)
    is_from_import: bool = False
    lineno: int = 0


class CodeAnalysis(BaseModel):
    """Complete code analysis result."""
    language: ProgrammingLanguage
    file_path: str
    source_hash: str
    lines_total: int = 0
    lines_code: int = 0
    lines_comment: int = 0
    lines_blank: int = 0
    syntax_valid: bool = False
    syntax_errors: list[str] = Field(default_factory=list)
    functions: list[FunctionInfo] = Field(default_factory=list)
    classes: list[ClassInfo] = Field(default_factory=list)
    imports: list[ImportInfo] = Field(default_factory=list)
    public_interface: list[str] = Field(default_factory=list)
    complexity_score: float = 0.0
    estimated_time_complexity: str = "O(1)"
    estimated_space_complexity: str = "O(1)"
    max_loop_depth: int = 0
    runtime_seconds: Optional[float] = None
    cpu_time_seconds: Optional[float] = None
    memory_peak_mb: Optional[float] = None
    warnings: list[str] = Field(default_factory=list)


# ── Mutation Schemas ─────────────────────────────────────────

class MutationCandidate(BaseModel):
    """A candidate mutation generated by the AI provider."""
    candidate_id: str
    source_code: str
    strategy: MutationStrategy = MutationStrategy.GENERAL
    explanation: str = ""
    expected_improvement: str = ""
    potential_risks: str = ""
    assumptions: str = ""
    content_hash: str = ""
    target_symbol: Optional[str] = None
    description: Optional[str] = None
    expected_benefit: Optional[str] = None
    complexity_analysis: Optional[dict[str, Any]] = None
    risks: list[str] = Field(default_factory=list)
    required_tests: list[str] = Field(default_factory=list)

    @field_validator("source_code")
    @classmethod
    def source_not_empty(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("Candidate source code cannot be empty.")
        return v


class MutationResponse(BaseModel):
    """Response from the AI provider containing candidates."""
    candidates: list[MutationCandidate] = Field(default_factory=list)
    model_id: str = ""
    usage: dict[str, Any] = Field(default_factory=dict)
    raw_response: Optional[str] = None


# ── Validation Schemas ───────────────────────────────────────

class ValidationResult(BaseModel):
    """Result of candidate validation."""
    candidate_id: str
    is_valid: bool = False
    syntax_valid: bool = False
    interface_preserved: bool = False
    size_valid: bool = False
    security_check_passed: bool = False
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


# ── Test Schemas ─────────────────────────────────────────────

class TestResult(BaseModel):
    """Result of running tests against a candidate."""
    __test__ = False

    candidate_id: str
    total_tests: int = 0
    passed: int = 0
    failed: int = 0
    skipped: int = 0
    errors: int = 0
    exit_code: int = 0
    duration_seconds: float = 0.0
    timed_out: bool = False
    output: str = ""
    failure_summaries: list[str] = Field(default_factory=list)
    coverage_percent: Optional[float] = None

    @property
    def all_passed(self) -> bool:
        return self.failed == 0 and self.errors == 0 and not self.timed_out and self.exit_code == 0


# ── Benchmark Schemas ────────────────────────────────────────

class BenchmarkMeasurement(BaseModel):
    """A single benchmark measurement."""
